import {test, expect} from '@playwright/test';

test('inline edit retries safely, persists to SQLite, and preserves original scan history', async ({page, request}) => {
  const base='http://127.0.0.1:8031/api';
  expect((await (await request.get(`${base}/health`)).json()).mock_vision).toBe(true);
  const scan=await (await request.post(`${base}/scans`,{data:{}})).json();
  const saved=await request.put(`${base}/scans/${scan.id}/review`,{data:{items:[{name:'Bananas',category:'Fruits',stock_status:'available',confirmed:true}]}});
  expect(saved.ok()).toBeTruthy();
  expect((await saved.json())[0].category).toBe('Fruits');
  await page.route('**/api/**', async route => {
    const url=new URL(route.request().url());url.host='127.0.0.1:8031';
    await route.fulfill({response:await request.fetch(url.toString(),{method:route.request().method(),data:route.request().postData()?JSON.parse(route.request().postData()!):undefined})});
  });
  await page.goto('/#inventory');
  const inventory=page.getByRole('region',{name:'My inventory'});
  await inventory.getByRole('button',{name:'Switch to table view'}).click();
  await inventory.getByRole('button',{name:'Edit Bananas'}).click();
  const editor=inventory.getByRole('form',{name:'Edit ingredient'});
  expect(await editor.evaluate(form=>form.closest('tr')?.previousElementSibling?.textContent?.includes('Bananas'))).toBeTruthy();
  await editor.getByLabel('Ingredient name').fill('Milk');
  await editor.getByLabel('Ingredient category').selectOption('Dairy');
  await editor.getByLabel('Ingredient stock').selectOption('low');
  await page.route('**/api/scans/*/review', route=>route.fulfill({status:503,json:{detail:'Test save failure. Retry.'}}),{times:1});
  await editor.getByRole('button',{name:'Save ingredient'}).click();
  await expect(editor.getByRole('alert')).toContainText('Test save failure');
  await expect(editor.getByLabel('Ingredient name')).toHaveValue('Milk');
  await expect(editor.getByLabel('Ingredient category')).toHaveValue('Dairy');
  await editor.getByRole('button',{name:'Save ingredient'}).click();
  await expect(editor).toHaveCount(0);
  await expect(inventory.getByRole('button',{name:'Edit Milk'})).toBeVisible();
  await page.reload();
  await expect(inventory.getByRole('heading',{name:'Milk',exact:true})).toBeVisible();
  await expect(inventory.locator('.inventory-item')).toContainText('Dairy');
  await expect(inventory.locator('.inventory-item')).toContainText('Running low');
  await expect(inventory.getByAltText('Reference photograph of Milk (not your fridge)')).toBeVisible();
  const original=await (await request.get(`${base}/scans/${scan.id}/items`)).json();
  expect(original[0].name).toBe('Bananas');
  const reviewed=(await (await request.get(`${base}/scans`)).json()).find((s:{status:string})=>s.status==='reviewed');
  const current=await (await request.get(`${base}/scans/${reviewed.id}/items`)).json();
  expect(current[0]).toMatchObject({name:'Milk',category:'Dairy',stock_status:'low',confirmed:true});

  await inventory.getByRole('button',{name:'Add ingredient'}).click();
  const add=inventory.getByRole('form',{name:'New ingredient'});
  await add.getByLabel('Ingredient name').fill('Cucumbers');
  await add.getByLabel('Ingredient category').selectOption('Vegetables');
  await add.getByLabel('Ingredient stock').selectOption('available');
  await add.getByRole('button',{name:'Save ingredient'}).click();
  await expect(inventory.getByRole('heading',{name:'Cucumbers',exact:true})).toBeVisible();
  await page.getByRole('navigation').getByRole('link',{name:'Dashboard',exact:true}).click();
  await expect(page.getByRole('article',{name:'Inventory ingredients'}).locator('strong')).toHaveText('2');
  await page.getByRole('navigation').getByRole('link',{name:'My Inventory',exact:true}).click();
  await page.reload();
  await expect(inventory.getByRole('heading',{name:'Cucumbers',exact:true})).toBeVisible();
  page.once('dialog',dialog=>dialog.dismiss());
  await inventory.getByRole('button',{name:'Delete Cucumbers',exact:true}).click();
  await expect(inventory.getByRole('heading',{name:'Cucumbers',exact:true})).toBeVisible();
  page.once('dialog',dialog=>dialog.accept());
  await inventory.getByRole('button',{name:'Delete Cucumbers',exact:true}).click();
  await expect(inventory.getByRole('heading',{name:'Cucumbers',exact:true})).toHaveCount(0);
  await page.reload();
  await expect(inventory.locator('.inventory-item')).toHaveCount(1);
  await expect(inventory.getByRole('heading',{name:'Milk',exact:true})).toBeVisible();
  expect((await (await request.get(`${base}/scans/${scan.id}/items`)).json())[0].name).toBe('Bananas');
});
